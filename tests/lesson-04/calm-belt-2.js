const devilFruit = "gomu-gomu";
let awakeningStatus;

if (devilFruit === "gomu-gomu") {
  awakeningStatus = "Gear 5 Unlocked!";
} else if (devilFruit === "mera-mera") {
  awakeningStatus = "Flame Emperor!";
} else if (devilFruit === "ope-ope") {
  awakeningStatus = "Room & Ope!";
} else if (devilFruit === "none") {
  awakeningStatus = "Normal Human";
} else {
  awakeningStatus = "Unknown Devil Fruit";
}
console.log(awakeningStatus);


